export function getWorldForChapter(chapterNumber: number): WorldDefinition {
  const world = CHAPTER_WORLDS.find((w) => w.chapter === chapterNumber);
  return world || CHAPTER_WORLDS[0];
}

export const getWorldByChapter = getWorldForChapter;

export function getWorldById(worldId: string): WorldDefinition | undefined {
  return CHAPTER_WORLDS.find((w) => w.id === worldId);
}
